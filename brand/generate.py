#!/usr/bin/env python3
"""Builds every platform file of Cairn's identity from brand/tokens.json and the artwork defined here.

    python3 -m pip install cairosvg pillow fonttools
    python3 brand/generate.py

Writes:
  brand/svg/                                   logo mark, wordmark, logos and icon masters (SVG)
  windows/src/Yippy.App/Themes/Light.xaml      colour tokens, light
  windows/src/Yippy.App/Themes/Dark.xaml       colour tokens, dark
  windows/src/Yippy.App/Themes/Tokens.xaml     radius, spacing and type size tokens
  windows/src/Yippy.App/Assets/AppIcon.ico     app, tray and installer icon
  windows/installer/Wizard*                    installer artwork
  Yippy/Resources/Assets.xcassets/Tokens/      colour tokens as named colours with light and dark appearances
  Yippy/Resources/Assets.xcassets/*Icon*       app icons, status bar icons, logo
  Yippy/Sources/Constants/DesignTokens.swift   radius, spacing and type size tokens

It fails if a text colour pair listed under "contrast" in tokens.json misses its minimum ratio, so the themes stay
readable whatever is edited. The wordmark is set in Inter Display (SIL Open Font License) and converted to outlines,
so no font ships with the apps; without the font installed the committed brand/svg/wordmark.svg is reused.
"""

