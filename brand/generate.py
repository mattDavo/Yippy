def colorset(light: Rgba, dark: Rgba) -> dict:
    def entry(c: Rgba, appearance: str | None) -> dict:
        e = {"idiom": "universal", "color": {"color-space": "srgb", "components": {
            "red": f"{c.r / 255:.3f}", "green": f"{c.g / 255:.3f}", "blue": f"{c.b / 255:.3f}", "alpha": f"{c.a / 255:.3f}"}}}
        if appearance:
            e["appearances"] = [{"appearance": "luminosity", "value": appearance}]
        return e
    return {"colors": [entry(light, None), entry(dark, "dark")], "info": {"author": "xcode", "version": 1}}


def write_json(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2) + "\n")


def write_colorsets(tokens: Tokens) -> None:
    folder = XCASSETS / "Tokens"
    if folder.exists():
        shutil.rmtree(folder)
    write_json(folder / "Contents.json", {"info": {"author": "xcode", "version": 1}, "properties": {"provides-namespace": True}})
    for key in tokens.themes["light"]:
        write_json(folder / f"{key}.colorset" / "Contents.json", colorset(tokens.themes["light"][key], tokens.themes["dark"][key]))


def swift_name(key: str) -> str:
    return key[0].lower() + key[1:]


def write_swift(tokens: Tokens) -> None:
    raw = tokens.raw
    out = [f"// {GENERATED_NOTE}", "", "import Cocoa", "",
           "/// Cairn's design tokens. Colours are named colours in Assets.xcassets/Tokens, with light and dark appearances.",
           "enum DesignTokens {", "",
           "    enum Color {"]
    for key in tokens.themes["light"]:
        out.append(f'        static var {swift_name(key)}: NSColor {{ named("{key}") }}')
    out += ["",
            "        private static func named(_ name: String) -> NSColor {",
            '            NSColor(named: NSColor.Name("Tokens/\\(name)")) ?? .labelColor',
            "        }",
            "    }", "",
            "    enum Radius {"]
    for key, value in raw["radius"].items():
        out.append(f"        static let {swift_name(key)}: CGFloat = {value}")
    out += ["    }", "", "    enum Space {"]
    for key, value in raw["spacing"].items():
        out.append(f"        static let {key.lower()}: CGFloat = {value}")
    out += ["    }", "", "    enum FontSize {"]
    for key, value in raw["type"].items():
        out.append(f"        static let {swift_name(key)}: CGFloat = {value}")
    out += ["    }", "}", ""]
    SWIFT_TOKENS.write_text("\n".join(out))


