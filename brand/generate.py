GROUPS = [
    ("Surfaces", ["PanelBackground", "PanelBorder", "CardBackground", "CardBorder", "CardHover", "CardSelected", "Divider"]),
    ("Text", ["PrimaryText", "SecondaryText", "DisabledText"]),
    ("Accent", ["Accent", "AccentHover", "AccentPressed", "TextOnAccent", "Link"]),
    ("Controls", ["ControlFill", "ControlFillHover", "ControlFillPressed", "ControlBorder", "SubtleHover", "SubtlePressed",
                  "SubtleSelected", "InputBackground", "InputBorder", "SegmentBackground", "SegmentSelected",
                  "ToggleOffBorder", "ScrollThumb"]),
    ("Keycaps: the panel's Ctrl+number hints and the shortcuts list", ["KeycapBackground", "KeycapBorder"]),
    ("Status", ["Favourite", "Danger", "Success"]),
]

COLOUR_XAML_HEADER = ('<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"\n'
                      '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">')
XAML_HEADER = ('<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"\n'
               '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"\n'
               '                    xmlns:sys="clr-namespace:System;assembly=mscorlib">\n')


def write_xaml_theme(tokens: Tokens, name: str) -> None:
    theme = tokens.themes[name]
    grouped = [key for _, keys in GROUPS for key in keys]
    missing = set(theme) - set(grouped)
    if missing:
        raise SystemExit(f"Add these tokens to a group in generate.py: {missing}")
    lines = [f"<!-- Cairn's {name} theme colours. ThemeManager swaps this dictionary when the Windows app theme changes.",
             f"     {THEME_NOTES[name]}",
             f"     {GENERATED_NOTE} -->",
             COLOUR_XAML_HEADER]
    for title, keys in GROUPS:
        lines.append(f"    <!-- {title} -->")
        for key in keys:
            lines.append(f'    <SolidColorBrush x:Key="Yippy.{key}" Color="{theme[key].xaml()}" />')
        lines.append("")
    lines[-1] = "</ResourceDictionary>"
    (WIN_APP / "Themes" / f"{name.capitalize()}.xaml").write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_xaml_metrics(tokens: Tokens) -> None:
    raw = tokens.raw
    lines = ["<!-- Cairn's shape, spacing and type size tokens, shared by both themes. Fluent.xaml and the views use these keys.",
             f"     {GENERATED_NOTE} -->",
             XAML_HEADER.rstrip("\n"),
             "    <!-- Corner radii: Small for keycaps and swatches, Control for buttons and inputs, Card for cards and",
             "         segments, Overlay for menus and flyouts, Window for the panel -->"]
    for key, value in raw["radius"].items():
        lines.append(f'    <CornerRadius x:Key="Yippy.Radius.{key}">{value}</CornerRadius>')
        lines.append(f'    <sys:Double x:Key="Yippy.RadiusValue.{key}">{value}</sys:Double>')
    lines += ["", "    <!-- Spacing: a 4 px scale -->"]
    for key, value in raw["spacing"].items():
        lines.append(f'    <sys:Double x:Key="Yippy.Space.{key}">{value}</sys:Double>')
    lines += ["", "    <!-- Type sizes (Fluent.xaml pairs them with weights and fonts) -->"]
    for key, value in raw["type"].items():
        lines.append(f'    <sys:Double x:Key="Yippy.FontSize.{key}">{value}</sys:Double>')
    lines.append("</ResourceDictionary>")
    (WIN_APP / "Themes" / "Tokens.xaml").write_text("\n".join(lines) + "\n", encoding="utf-8")


