@dataclass(frozen=True)
class Rgba:
    r: int
    g: int
    b: int
    a: int = 255

    @staticmethod
    def parse(text: str) -> "Rgba":
        """#RRGGBB, or #AARRGGBB like XAML."""
        h = text.lstrip("#")
        if len(h) == 6:
            return Rgba(int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))
        if len(h) == 8:
            return Rgba(int(h[2:4], 16), int(h[4:6], 16), int(h[6:8], 16), int(h[0:2], 16))
        raise ValueError(f"Not a colour: {text}")

    def xaml(self) -> str:
        if self.a == 255:
            return f"#{self.r:02X}{self.g:02X}{self.b:02X}"
        return f"#{self.a:02X}{self.r:02X}{self.g:02X}{self.b:02X}"

    def over(self, background: "Rgba") -> "Rgba":
        a = self.a / 255
        mix = lambda f, b: round(f * a + b * (1 - a))
        return Rgba(mix(self.r, background.r), mix(self.g, background.g), mix(self.b, background.b))

    def luminance(self) -> float:
        def channel(c: int) -> float:
            s = c / 255
            return s / 12.92 if s <= 0.03928 else ((s + 0.055) / 1.055) ** 2.4
        return 0.2126 * channel(self.r) + 0.7152 * channel(self.g) + 0.0722 * channel(self.b)


def contrast(a: Rgba, b: Rgba) -> float:
    la, lb = sorted((a.luminance(), b.luminance()), reverse=True)
    return (la + 0.05) / (lb + 0.05)


class Tokens:
    def __init__(self, path: Path):
        self.raw = json.loads(path.read_text())
        self.palette = {k: Rgba.parse(v) for k, v in self.raw["palette"].items()}
        self.themes = {name: {k: self.resolve(v) for k, v in theme.items()} for name, theme in self.raw["themes"].items()}
        light, dark = self.themes["light"].keys(), self.themes["dark"].keys()
        if list(light) != list(dark):
            raise SystemExit(f"The light and dark themes must define the same tokens in the same order: {set(light) ^ set(dark)}")

    def resolve(self, value: str) -> Rgba:
        return self.palette[value] if value in self.palette else Rgba.parse(value)

    def p(self, name: str) -> str:
        """A palette colour as #RRGGBB, for the artwork."""
        return self.palette[name].xaml()

    def check_contrast(self) -> None:
        failures = []
        for theme_name, theme in self.themes.items():
            for fg, bg, minimum in self.raw["contrast"]:
                background = theme[bg].over(theme["PanelBackground"])
                ratio = contrast(theme[fg].over(background), background)
                if ratio < minimum:
                    failures.append(f"{theme_name}: {fg} on {bg} is {ratio:.2f}:1, needs {minimum}:1")
        if failures:
            raise SystemExit("Contrast check failed:\n  " + "\n  ".join(failures))


