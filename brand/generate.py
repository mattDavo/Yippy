def pebble(cx: float, cy: float, w: float, h: float, rotation: float, lean: float = 0.06, k: float = 0.74) -> str:
    """A flat river stone: a squarish ellipse whose top leans a little, so a stack of them reads as stones, not pills."""
    dx = w * lean / 2
    rx, ry = w / 2, h / 2
    pts = {
        "right": (cx + rx, cy), "bottom": (cx + dx, cy + ry), "left": (cx - rx, cy), "top": (cx - dx, cy - ry),
    }
    (r, b, l, t) = (pts["right"], pts["bottom"], pts["left"], pts["top"])
    d = (f"M{r[0]:.1f},{r[1]:.1f} "
         f"C{r[0]:.1f},{r[1] + k * ry:.1f} {b[0] + k * rx:.1f},{b[1]:.1f} {b[0]:.1f},{b[1]:.1f} "
         f"C{b[0] - k * rx:.1f},{b[1]:.1f} {l[0]:.1f},{l[1] + k * ry:.1f} {l[0]:.1f},{l[1]:.1f} "
         f"C{l[0]:.1f},{l[1] - k * ry:.1f} {t[0] - k * rx:.1f},{t[1]:.1f} {t[0]:.1f},{t[1]:.1f} "
         f"C{t[0] + k * rx:.1f},{t[1]:.1f} {r[0]:.1f},{r[1] - k * ry:.1f} {r[0]:.1f},{r[1]:.1f} Z")
    return f'<path d="{d}" transform="rotate({rotation} {cx} {cy})"'


@dataclass(frozen=True)
class Stone:
    cx: float
    cy: float
    w: float
    h: float
    rotation: float


# The mark on a 1024 grid: three stones, the newest (top) one in Ember. Widths step down by about a quarter.
STONES = [Stone(512, 668, 540, 172, -3), Stone(500, 490, 410, 144, 4), Stone(524, 336, 280, 122, -5)]
# At 16-32 px the stones get thicker and the gaps wider, so they don't blur into one shape
SMALL_STONES = [Stone(512, 716, 760, 236, -2), Stone(500, 482, 580, 200, 3), Stone(526, 268, 400, 172, -4)]


def stones_svg(t: Tokens, stones: list[Stone], top: str, rest: str, shadows: bool, ids: str) -> str:
    parts = []
    if shadows:
        for i, s in enumerate(stones):
            parts.append(f'<ellipse cx="{s.cx + 6}" cy="{s.cy + s.h * 0.46}" rx="{s.w * 0.5}" ry="{s.h * 0.24}" '
                         f'fill="url(#{ids}shadow)"/>')
    for i, s in enumerate(stones):
        fill = top if i == len(stones) - 1 else rest
        parts.append(pebble(s.cx, s.cy, s.w, s.h, s.rotation) + f' fill="{fill}"/>')
    return "\n    ".join(parts)


def defs(t: Tokens, ids: str = "") -> str:
    return f"""<defs>
    <linearGradient id="{ids}plate" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="{t.p('stone-750')}"/>
      <stop offset="1" stop-color="{t.p('stone-950')}"/>
    </linearGradient>
    <linearGradient id="{ids}stone" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="{t.p('stone-50')}"/>
      <stop offset="1" stop-color="{t.p('stone-300')}"/>
    </linearGradient>
    <linearGradient id="{ids}ember" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="{t.p('ember-300')}"/>
      <stop offset="1" stop-color="{t.p('ember-500')}"/>
    </linearGradient>
    <linearGradient id="{ids}beta" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#4C6B57"/>
      <stop offset="1" stop-color="#1F2E25"/>
    </linearGradient>
    <radialGradient id="{ids}shadow">
      <stop offset="0" stop-color="#000" stop-opacity="0.45"/>
      <stop offset="1" stop-color="#000" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="{ids}sheen" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#FFFFFF" stop-opacity="0.10"/>
      <stop offset="0.5" stop-color="#FFFFFF" stop-opacity="0"/>
    </linearGradient>
  </defs>"""


def app_icon_mac(t: Tokens, beta: bool = False) -> str:
    """macOS icon grid: an 824 px rounded square centred on 1024, with its own soft shadow."""
    plate = "url(#beta)" if beta else "url(#plate)"
    shadow = "".join(f'<rect x="{100 - i}" y="{100 + 10 - i + i * 0.6}" width="{824 + 2 * i}" height="{824 + 2 * i}" '
                     f'rx="{185 + i}" fill="#000" fill-opacity="0.035"/>' for i in range(0, 24, 3))
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">
  {defs(t)}
  {shadow}
  <rect x="100" y="100" width="824" height="824" rx="185" fill="{plate}"/>
  <rect x="100" y="100" width="824" height="824" rx="185" fill="url(#sheen)"/>
  <rect x="100.5" y="100.5" width="823" height="823" rx="184.5" fill="none" stroke="#FFFFFF" stroke-opacity="0.08"/>
  <g transform="translate(512 512) scale(0.86) translate(-512 -512)">
    {stones_svg(t, STONES, 'url(#ember)', 'url(#stone)', True, '')}
  </g>
</svg>
"""


def app_icon_windows(t: Tokens, small: bool = False) -> str:
    """Windows: a full-bleed rounded square, so the icon reads at taskbar and tray sizes."""
    stones = SMALL_STONES if small else STONES
    scale = 0.84 if small else 0.9
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">
  {defs(t)}
  <rect x="16" y="16" width="992" height="992" rx="{200 if small else 220}" fill="url(#plate)"/>
  <rect x="16" y="16" width="992" height="992" rx="{200 if small else 220}" fill="url(#sheen)"/>
  <g transform="translate(512 512) scale({scale}) translate(-512 -512)">
    {stones_svg(t, stones, 'url(#ember)', 'url(#stone)', not small, '')}
  </g>
</svg>
"""


def mark(t: Tokens, rest: str, top: str | None = None, small: bool = False) -> str:
    """The stones alone, on transparent: for logos, the status bar and the installer."""
    stones = SMALL_STONES if small else STONES
    top = top or "url(#ember)"
    xs = [s.cx - s.w / 2 for s in stones] + [s.cx + s.w / 2 for s in stones]
    ys = [s.cy - s.h / 2 for s in stones] + [s.cy + s.h / 2 for s in stones]
    pad = 24
    x0, y0, x1, y1 = min(xs) - pad, min(ys) - pad, max(xs) + pad, max(ys) + pad
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="{x0:.0f} {y0:.0f} {x1 - x0:.0f} {y1 - y0:.0f}">
  {defs(t)}
  {stones_svg(t, stones, top, rest, False, '')}
</svg>
"""


def status_bar_icon(beta: bool) -> str:
    """An 18 pt template image: black stones that macOS tints for the menu bar. The Beta build's are hollow."""
    stones = [Stone(9, 13.6, 15.5, 5.2, -3), Stone(8.8, 8.6, 11.6, 4.4, 4), Stone(9.3, 4.2, 7.6, 3.6, -5)]
    paint = 'fill="none" stroke="#000" stroke-width="1.3"' if beta else 'fill="#000"'
    shapes = "\n  ".join(pebble(s.cx, s.cy, s.w, s.h, s.rotation) + f" {paint}/>" for s in stones)
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 18 18">\n  {shapes}\n</svg>\n'


@dataclass(frozen=True)
class Wordmark:
    group: str  # an SVG path, baseline at y=0, in font units
    width: float
    x_height: float
    top: float  # the i's dot
    bottom: float


def wordmark_paths(color: str) -> Wordmark | None:
    """'cairn' in Inter Display SemiBold as outlines, or None without the font."""
    try:
        from fontTools.pens.svgPathPen import SVGPathPen
        from fontTools.pens.transformPen import TransformPen
        from fontTools.ttLib import TTFont
        path = subprocess.run(["fc-match", "-f", "%{file}", "Inter Display:style=SemiBold"],
                              capture_output=True, text=True, check=True).stdout
        if "InterDisplay" not in path:
            return None
        font = TTFont(path)
    except (ImportError, OSError, subprocess.CalledProcessError):
        return None
    glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
    units = font["head"].unitsPerEm
    tracking = -0.02 * units
    x, d = 0.0, []
    for ch in "cairn":
        name = cmap[ord(ch)]
        pen = SVGPathPen(glyphs)
        glyphs[name].draw(TransformPen(pen, (1, 0, 0, -1, x, 0)))
        d.append(pen.getCommands())
        x += glyphs[name].width + tracking
    return Wordmark(f'<path fill="{color}" d="{" ".join(d)}"/>', x - tracking, font["OS/2"].sxHeight,
                    top=0.75 * units, bottom=0.02 * units)


def write_wordmark_and_logos(t: Tokens) -> None:
    for theme, color in (("light", t.p("stone-900")), ("dark", "#F5F1EB")):
        built = wordmark_paths(color)
        target = SVG_DIR / f"wordmark-{theme}.svg"
        if built is None:
            if not target.exists():
                raise SystemExit("Inter Display isn't installed and brand/svg has no wordmark to reuse.")
            continue
        pad = 0.02 * built.top
        target.write_text(f'<svg xmlns="http://www.w3.org/2000/svg" '
                          f'viewBox="{-pad:.0f} {-built.top - pad:.0f} {built.width + 2 * pad:.0f} {built.top + built.bottom + 2 * pad:.0f}">\n'
                          f"  {built.group}\n</svg>\n")
        # Horizontal logo: the mark, then the wordmark set on the mark's baseline
        stones_mark = mark(t, "url(#stone)" if theme == "dark" else t.p("stone-700"))
        inner_mark = stones_mark.split("\n", 1)[1].rsplit("</svg>", 1)[0]
        vb = [float(v) for v in stones_mark.split('viewBox="')[1].split('"')[0].split()]
        mark_h = 560
        mark_scale = mark_h / vb[3]
        mark_w = vb[2] * mark_scale
        # The x-height matches the two lower stones' height; the baseline sits on the bottom stone's middle
        text_scale = mark_h * 0.42 / built.x_height
        gap = mark_h * 0.16
        total_w = mark_w + gap + built.width * text_scale
        baseline = mark_h * 0.84
        (SVG_DIR / f"logo-{theme}.svg").write_text(
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {total_w:.0f} {mark_h:.0f}">\n'
            f'  <g transform="scale({mark_scale:.4f}) translate({-vb[0]:.1f} {-vb[1]:.1f})">{inner_mark}</g>\n'
            f'  <g transform="translate({mark_w + gap:.1f} {baseline:.1f}) scale({text_scale:.4f})">{built.group}</g>\n'
            f"</svg>\n")


def png(svg: str, size: int, height: int | None = None) -> Image.Image:
    data = cairosvg.svg2png(bytestring=svg.encode(), output_width=size, output_height=height or size)
    return Image.open(io.BytesIO(data)).convert("RGBA")


def write_artwork(t: Tokens) -> None:
    SVG_DIR.mkdir(parents=True, exist_ok=True)
    masters = {
        "app-icon-macos.svg": app_icon_mac(t),
        "app-icon-macos-beta.svg": app_icon_mac(t, beta=True),
        "app-icon-windows.svg": app_icon_windows(t),
        "app-icon-windows-small.svg": app_icon_windows(t, small=True),
        "mark.svg": mark(t, "url(#stone)"),
        "mark-on-light.svg": mark(t, t.p("stone-700")),
        "status-bar.svg": status_bar_icon(beta=False),
        "status-bar-beta.svg": status_bar_icon(beta=True),
    }
    for name, svg in masters.items():
        (SVG_DIR / name).write_text(svg)
    write_wordmark_and_logos(t)

    # macOS app icons
    for folder, svg in (("AppIcon.appiconset", masters["app-icon-macos.svg"]), ("BetaAppIcon.appiconset", masters["app-icon-macos-beta.svg"])):
        for size in (16, 32, 64, 128, 256, 512, 1024):
            png(svg, size).save(XCASSETS / folder / f"{size}.png", optimize=True)

    # The logo the About, Help and Welcome windows show
    logo_set = XCASSETS / "AppLogo.imageset"
    logo_set.mkdir(exist_ok=True)
    png(masters["app-icon-macos.svg"], 1024).save(logo_set / "AppLogo.png", optimize=True)
    write_json(logo_set / "Contents.json", {"images": [{"idiom": "universal", "filename": "AppLogo.png"}],
                                            "info": {"author": "xcode", "version": 1}})

    # Menu bar template icons
    for name, svg in (("StatusBarIcon", masters["status-bar.svg"]), ("BetaStatusBarIcon", masters["status-bar-beta.svg"])):
        folder = XCASSETS / f"{name}.imageset"
        folder.mkdir(exist_ok=True)
        png(svg, 18).save(folder / f"{name}.png", optimize=True)
